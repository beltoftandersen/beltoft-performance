<?php
namespace BeltoftPerformance\Rules;

use BeltoftPerformance\Request\RouteMap;

defined( 'ABSPATH' ) || exit;

/** Writes the unload rules + route table as a PHP file the mu loader includes (no DB read before plugins load). */
final class Compiler {
	/** The rule file, computed exactly as the mu loader does (it runs before wp_upload_dir() can be called). */
	public static function file(): string {
		return self::path_for( WP_CONTENT_DIR, ABSPATH, defined( 'UPLOADS' ) ? UPLOADS : null );
	}

	/** Pure: same logic as beltoft_performance_rules_path() in the mu loader. */
	public static function path_for( string $content_dir, string $abspath, ?string $uploads ): string {
		$base = ( null !== $uploads && '' !== trim( $uploads, '/' ) ) ? rtrim( $abspath, '/' ) . '/' . trim( $uploads, '/' ) : rtrim( $content_dir, '/' ) . '/uploads';
		return $base . '/beltoft-performance/rules.php';
	}

	public static function compile( array $rules, array $routes, string $file, string $secret = '' ): bool {
		$unload = array();
		$urls   = array();
		foreach ( $rules as $r ) {
			if ( 'unload' !== $r->tier() ) {
				continue;
			}
			foreach ( $r->hosts as $h ) {
				foreach ( $r->pages as $p ) {
					if ( 0 === strpos( (string) $p, 'url:' ) ) {
						// Scopes were normalised and checked when stored: only a cheap shape check here (no re-classifying).
						if ( preg_match( '#^url:(/(?:[^/\s]+/)*)$#', strtolower( (string) $p ), $m ) ) {
							$path                  = $m[1];
							$urls[ $h ][ $path ][] = $r->name();
							$urls[ $h ][ $path ]   = array_values( array_unique( $urls[ $h ][ $path ] ) );
							sort( $urls[ $h ][ $path ] );
						}
						continue;
					}
					if ( 0 === strpos( (string) $p, 'template:' ) ) {
						continue;
					}
					$unload[ $h ][ $p ][] = $r->name();
					$unload[ $h ][ $p ]   = array_values( array_unique( $unload[ $h ][ $p ] ) );
					sort( $unload[ $h ][ $p ] );
				}
			}
		}
		$data = array( 'v' => 1, 'routes' => $routes, 'unload' => $unload, 'unload_urls' => $urls );
		if ( '' !== $secret ) {
			$data['check_secret'] = $secret;
		}
		$php  = "<?php\n// Generated by beltoft-performance. Do not edit: change rules in Settings › Performance.\nreturn " . var_export( $data, true ) . ";\n";

		// Validate the generated PHP.
		try {
			token_get_all( $php, TOKEN_PARSE );
		} catch ( \ParseError $e ) {
			return false;
		}

		$dir  = dirname( $file );
		if ( ! is_dir( $dir ) && ! @mkdir( $dir, 0755, true ) ) {
			return false;
		}
		if ( ! is_file( $dir . '/index.php' ) ) {
			@file_put_contents( $dir . '/index.php', '<?php // Silence is golden.' );
		}
		$tmp = $file . '.' . getmypid() . '.tmp';
		$bytes = file_put_contents( $tmp, $php );
		if ( false === $bytes || $bytes !== strlen( $php ) ) {
			@unlink( $tmp );
			return false;
		}
		@chmod( $tmp, 0640 );
		if ( ! rename( $tmp, $file ) ) {
			@unlink( $tmp );
			return false;
		}

		// Invalidate opcode cache.
		if ( function_exists( 'opcache_invalidate' ) ) {
			opcache_invalidate( $file, true );
		}

		return true;
	}

	/** Pure: the error to show after a rule change (Store result + compile result), or null when both worked. */
	public static function change_error( $store_result, bool $compiled ): ?string {
		if ( true !== $store_result ) {
			return (string) $store_result;
		}
		return $compiled ? null : __( 'The rule was saved but the rules file was not written, so the loader still uses the old rules.', 'beltoft-performance' );
	}

	public static function compile_from_store(): bool {
		return self::compile( Store::all(), RouteMap::build(), self::file(), \BeltoftPerformance\Check\Signature::secret() );
	}
}
